function load(address: string, lines: readonly string[]): DeliveryRecord[] {
  return lines.map((line) => {
    const [date, time, outcome, home, neighbor, driver] = line.split("|");
    return {
      id: "",
      date: date ?? "",
      time: time ?? "",
      address,
      customer: customers[address] ?? "Sample Customer",
      outcome: (outcome === "Failed" ? "Failed" : "Delivered") as DeliveryOutcome,
      recipientHome: home === "Yes",
      neighborReceiver: neighbor && neighbor !== "-" ? neighbor : null,
      driver: driver ?? "Driver 01",
      dayOfWeek: dayName(date ?? ""),
    };
  });
}

